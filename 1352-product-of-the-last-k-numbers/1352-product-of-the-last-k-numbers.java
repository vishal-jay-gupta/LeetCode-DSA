import java.util.*;

class ProductOfNumbers {
    ArrayList<Integer> list;
    public ProductOfNumbers() {
        list = new ArrayList<>();
    }
    
    public void add(int num) {
        list.add(num);
    }
    
    public int getProduct(int k) {
        int n = list.size()-1;
        int ans = 1;
        while(k > 0){
            ans *= list.get(n);
            n--;
            k--;
        }
        System.out.println();
        return ans;
    }
}

